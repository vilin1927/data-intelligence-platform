-- schema/103_b91_vinsight_staging_id_identity.sql
-- Bundle B9.1 — Vinsight staging tables: add IDENTITY to id columns missing
--               an auto-increment default (prod hotfix).
-- ════════════════════════════════════════════════════════════════════════════
-- Date:  2026-04-28
--        dead-lettered with "null value in column \"id\" violates not-null
--        constraint". Connector at connectors/vinsight.py:342-348 omits `id`
--        on INSERT, expecting auto-increment; staging table has
--        `id INTEGER NOT NULL` with no DEFAULT / sequence / IDENTITY.
--
-- Pre-state (verified on prod via SSH 2026-04-28):
--   ┌─────────────────────────────────────────────┬─────────────┬───────────┐
--   │ table                                       │ has default │ rows      │
--   ├─────────────────────────────────────────────┼─────────────┼───────────┤
--   │ staging_vinsight_stock_items                │ NO          │ 0         │
--   │ staging_vinsight_wine_batches               │ NO          │ 0         │
--   │ staging_vinsight_vessels                    │ NO          │ 0         │
--   │ staging_vinsight_packaging_operations       │ NO          │ 0         │
--   │ staging_vinsight_sales_orders   (control)   │ YES (seq)   │ 362,506   │
--   │ staging_vinsight_contacts       (control)   │ YES (seq)   │ 139,189   │
--   └─────────────────────────────────────────────┴─────────────┴───────────┘
-- The 4 defective tables are all empty, so IDENTITY can start at 1 with no
-- collision risk. The 2 control tables already work and are NOT touched.
--
-- Fix: ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (Postgres ≥10
-- syntax — prod is 17.9). "BY DEFAULT" (not "ALWAYS") so the connector's
-- existing INSERT path keeps working when it omits id, AND any explicit-id
-- ETL could still pass an id manually if needed.
--
-- data movement, no downtime, no FK rewrites.
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

-- ────────────────────────────────────────────────────────────────────────────
-- 1. Pre-condition assertion
-- ────────────────────────────────────────────────────────────────────────────
DO $$
BEGIN
    -- All 4 defective tables must exist.
    IF to_regclass('public.staging_vinsight_stock_items') IS NULL THEN
        RAISE EXCEPTION 'staging_vinsight_stock_items missing';
    END IF;
    IF to_regclass('public.staging_vinsight_wine_batches') IS NULL THEN
        RAISE EXCEPTION 'staging_vinsight_wine_batches missing';
    END IF;
    IF to_regclass('public.staging_vinsight_vessels') IS NULL THEN
        RAISE EXCEPTION 'staging_vinsight_vessels missing';
    END IF;
    IF to_regclass('public.staging_vinsight_packaging_operations') IS NULL THEN
        RAISE EXCEPTION 'staging_vinsight_packaging_operations missing';
    END IF;
END $$;

-- ────────────────────────────────────────────────────────────────────────────
-- 2. Add IDENTITY to each defective table.
--    Wrapped per-table in a DO block that no-ops if IDENTITY is already
--    present — re-applies cleanly after a partial run.
-- ────────────────────────────────────────────────────────────────────────────
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema='public'
           AND table_name='staging_vinsight_stock_items'
           AND column_name='id'
           AND is_identity='YES'
    ) THEN
        EXECUTE 'ALTER TABLE staging_vinsight_stock_items
                 ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY';
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema='public'
           AND table_name='staging_vinsight_wine_batches'
           AND column_name='id'
           AND is_identity='YES'
    ) THEN
        EXECUTE 'ALTER TABLE staging_vinsight_wine_batches
                 ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY';
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema='public'
           AND table_name='staging_vinsight_vessels'
           AND column_name='id'
           AND is_identity='YES'
    ) THEN
        EXECUTE 'ALTER TABLE staging_vinsight_vessels
                 ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY';
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema='public'
           AND table_name='staging_vinsight_packaging_operations'
           AND column_name='id'
           AND is_identity='YES'
    ) THEN
        EXECUTE 'ALTER TABLE staging_vinsight_packaging_operations
                 ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY';
    END IF;
END $$;

-- ────────────────────────────────────────────────────────────────────────────
-- 3. Post-state assertion — every Vinsight staging table's id col now has a
--    default (sequence OR identity). Lists all four defective tables; if any
--    still lacks a default, abort the txn so we don't silently leave a half-
--    fixed state.
-- ────────────────────────────────────────────────────────────────────────────
DO $$
DECLARE
    v_offenders TEXT;
BEGIN
    SELECT string_agg(table_name, ', ') INTO v_offenders
      FROM information_schema.columns
     WHERE table_schema='public'
       AND column_name='id'
       AND is_nullable='NO'
       AND column_default IS NULL
       AND is_identity='NO'
       AND table_name IN (
            'staging_vinsight_stock_items',
            'staging_vinsight_wine_batches',
            'staging_vinsight_vessels',
            'staging_vinsight_packaging_operations'
       );

    IF v_offenders IS NOT NULL THEN
        RAISE EXCEPTION
          'staging_vinsight_* tables still lack id default after ALTER: %',
          v_offenders;
    END IF;

    RAISE NOTICE
      'B9.1 schema/103 OK: 4 staging_vinsight_* tables now have IDENTITY on id.';
END $$;

INSERT INTO schema_migrations (version, applied_at, source)
VALUES ('103_b91_vinsight_staging_id_identity', NOW(), 'live-apply')
ON CONFLICT (version) DO NOTHING;

COMMIT;

